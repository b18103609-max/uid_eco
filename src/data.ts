function mk(
  num: string, code: string, subject: string, description: string,
  formedAt: string, plannedEnd: string, contractNo: string,
  customer: string, contractor: string, linkedViolations: number[], claimsCount: number,
  protocolNo: string, protocolDate: string, responsible: string, status: PkmStatus,
): Pkm {
  return {
    id: 'pkm-' + num.replace('/', '-'),
    num, code, contractSubject: subject, description,
    formedAt, plannedEnd, contractNo, customer, contractor,
    linkedViolations, claimsCount,
    protocolNo, protocolDate, responsible, status,
    attachments: [], comment: '',
    history: [{ date: formedAt, from: null, to: 'Новый', responsible, comment: 'Мероприятие создано' }],
  };
}

